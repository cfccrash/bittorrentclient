"""Generates BitTorrentClient.ico (for the .exe) and icon_data.py (window icon) - pure standard library.
Run:  python make_icon.py [preview.png]"""
import base64
import math
import struct
import sys
import zlib


def _inside_round_rect(x, y, x0, y0, x1, y1, r):
    cx = min(max(x, x0 + r), x1 - r)
    cy = min(max(y, y0 + r), y1 - r)
    return (x - cx) ** 2 + (y - cy) ** 2 <= r * r and x0 <= x <= x1 and y0 <= y <= y1


def _in_triangle(px, py, a, b, c):
    def sign(p1, p2, p3):
        return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
    p = (px, py)
    d1, d2, d3 = sign(p, a, b), sign(p, b, c), sign(p, c, a)
    return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))


def _mix(c1, c2, t):
    t = min(1.0, max(0.0, t))
    return tuple(c1[i] + (c2[i] - c1[i]) * t for i in range(3))


def render(size, ss=4):
    """RGBA rows: the Aurora "night glow" icon - a dark navy tile (like the app window) with a thin blue edge, a soft
    blue glow, and a download arrow + tray shading from sky blue to the theme's violet."""
    navy_top, navy_bottom = (0x0E, 0x18, 0x3A), (0x04, 0x06, 0x0E)       # palette bg / a lighter navy
    edge, glow = (0x28, 0x3A, 0x6E), (0x1C, 0x3C, 0x96)
    sky, violet = (0x96, 0xC8, 0xFF), (0x7A, 0x5C, 0xFF)                  # accent_hover-ish -> palette "glow"
    rows = []
    for j in range(size):
        row = bytearray()
        for i in range(size):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sj in range(ss):
                for si in range(ss):
                    x, y = (i + (si + 0.5) / ss) / size, (j + (sj + 0.5) / ss) / size
                    if not _inside_round_rect(x, y, 0.04, 0.04, 0.96, 0.96, 0.22):
                        continue
                    if not _inside_round_rect(x, y, 0.065, 0.065, 0.935, 0.935, 0.20):
                        col = edge
                    else:
                        col = _mix(navy_top, navy_bottom, y * 0.9)
                        d = math.hypot(x - 0.5, y - 0.52)
                        col = _mix(col, glow, min(1.0, max(0.0, 0.42 - d) * 1.6))      # glow behind the arrow
                        if (0.44 <= x <= 0.56 and 0.19 <= y <= 0.50                       # arrow shaft
                                or _in_triangle(x, y, (0.28, 0.46), (0.72, 0.46), (0.5, 0.69))  # arrow head
                                or _inside_round_rect(x, y, 0.26, 0.76, 0.74, 0.82, 0.03)):     # tray
                            col = _mix(sky, violet, (y - 0.19) / 0.63)
                    acc[0] += col[0]; acc[1] += col[1]; acc[2] += col[2]; acc[3] += 1
            n = ss * ss
            if acc[3]:
                row += bytes((int(acc[0] / acc[3]), int(acc[1] / acc[3]), int(acc[2] / acc[3]), int(255 * acc[3] / n)))
            else:
                row += b"\x00\x00\x00\x00"
        rows.append(bytes(row))
    return rows


def png(size):
    rows = render(size, 4 if size >= 32 else 6)
    raw = b"".join(b"\x00" + r for r in rows)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def main():
    sizes = (16, 24, 32, 48, 64, 128, 256)
    images = [(s, png(s)) for s in sizes]
    head = struct.pack("<HHH", 0, 1, len(images))
    offset, entries, blobs = 6 + 16 * len(images), b"", b""
    for s, data in images:
        entries += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(data), offset)
        blobs += data
        offset += len(data)
    open("BitTorrentClient.ico", "wb").write(head + entries + blobs)
    open("icon_data.py", "w").write('"""Generated by make_icon.py - window icon (64px PNG)."""\nPNG_B64 = "%s"\n'
                                    % base64.b64encode(dict(images)[64]).decode())
    if len(sys.argv) > 1:                       # optional: python make_icon.py preview.png  (the 256 px image)
        open(sys.argv[1], "wb").write(dict(images)[256])
    print("wrote BitTorrentClient.ico (%d sizes) and icon_data.py" % len(images))


if __name__ == "__main__":
    main()
