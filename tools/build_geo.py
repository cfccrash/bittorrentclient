"""Regenerates geo_data.py (IPv4 -> country ranges) and flags_data.py (flag PNGs) from public sources.
Needs: npm, rsvg-convert. Run from the project folder:  python3 tools/build_geo.py
  - IP ranges:  npm @ip-location-db/dbip-country   (DB-IP Lite, CC BY 4.0, https://db-ip.com)
  - Flags:      npm flag-icons                     (MIT, https://github.com/lipis/flag-icons)"""
import base64, bisect, json, os, struct, subprocess, sys, tarfile, tempfile, zlib

OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
work = tempfile.mkdtemp()


def npm_pack(pkg):
    subprocess.check_call(["npm", "pack", pkg, "--silent"], cwd=work, stdout=subprocess.DEVNULL)
    tgz = [f for f in os.listdir(work) if f.endswith(".tgz") and pkg.split("/")[-1] in f][-1]
    d = os.path.join(work, tgz[:-4])
    with tarfile.open(os.path.join(work, tgz)) as t:
        t.extractall(d)
    return os.path.join(d, "package")


# ---- IPv4 ranges -> compact binary
pk = npm_pack("@ip-location-db/dbip-country")
rows = []
for line in open(os.path.join(pk, "dbip-country-ipv4-num.csv")):
    a, b, cc = line.strip().split(",")
    rows.append((int(a), int(b), cc))
rows.sort()
codes = sorted({r[2] for r in rows})
idx = {c: i for i, c in enumerate(codes)}
# keep only range starts; a gap (unassigned space) is a range with the "unknown" code
UNK = len(codes)
starts, vals, prev_end = [], [], -1
for a, b, cc in rows:
    if a > prev_end + 1:
        starts.append(prev_end + 1); vals.append(UNK)
    if vals and vals[-1] == idx[cc] and a == prev_end + 1:
        pass
    else:
        starts.append(a); vals.append(idx[cc])
    prev_end = b
starts.append(prev_end + 1); vals.append(UNK)
blob = zlib.compress(struct.pack(">%dI" % len(starts), *starts) + bytes(vals), 9)
with open(os.path.join(OUT, "geo_data.py"), "w") as f:
    f.write('"""IPv4 -> country data derived from DB-IP Lite (https://db-ip.com), CC BY 4.0. Generated by tools/build_geo.py."""\n')
    f.write("CODES = %r\nCOUNT = %d\nBLOB = %r\n" % (codes, len(starts), base64.b64encode(blob).decode()))
print("ranges:", len(starts), "countries:", len(codes), "blob KB:", len(blob) // 1024)

# ---- flags + names
fp = npm_pack("flag-icons")
names = {c["code"].upper(): c["name"] for c in json.load(open(os.path.join(fp, "country.json")))}
flags = {}
for cc in codes:
    svg = os.path.join(fp, "flags", "4x3", cc.lower() + ".svg")
    if not os.path.exists(svg):
        continue
    pair = []
    for w, h in ((20, 15), (40, 30)):
        png = subprocess.check_output(["rsvg-convert", "-w", str(w), "-h", str(h), svg])
        pair.append(base64.b64encode(zlib.compress(png, 9)).decode())
    flags[cc] = pair
with open(os.path.join(OUT, "flags_data.py"), "w") as f:
    f.write('"""Country names and 20x15 / 40x30 PNG flags (zlib+base64) from flag-icons (MIT). Generated by tools/build_geo.py."""\n')
    f.write("NAMES = %r\nFLAGS = %r\n" % ({c: names.get(c, c) for c in codes}, flags))
print("flags:", len(flags), "missing:", [c for c in codes if c not in flags])
