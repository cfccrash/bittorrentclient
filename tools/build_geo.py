"""Regenerates geo_data.py (IPv4 + IPv6 -> country ranges) and flags_data.py (flag PNGs) from public sources.
Needs: npm (and rsvg-convert for the flags). Run from the project folder:  python3 tools/build_geo.py [--ip-only]
  - IP ranges:  npm @ip-location-db/dbip-country   (DB-IP Lite, CC BY 4.0, https://db-ip.com)
  - Flags:      npm flag-icons                     (MIT, https://github.com/lipis/flag-icons)
--ip-only rebuilds geo_data.py alone: flags_data.py keeps the flags made by tools/flags_from_pdf.py."""
import base64, json, os, struct, subprocess, sys, tarfile, tempfile, zlib

OUT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
work = tempfile.mkdtemp()


def npm_pack(pkg):
    subprocess.check_call(["npm", "pack", pkg, "--silent"], cwd=work, stdout=subprocess.DEVNULL, shell=os.name == "nt")
    tgz = [f for f in os.listdir(work) if f.endswith(".tgz") and pkg.split("/")[-1] in f][-1]
    d = os.path.join(work, tgz[:-4])
    with tarfile.open(os.path.join(work, tgz)) as t:
        t.extractall(d, filter="data")
    return os.path.join(d, "package")


def read(path, shift):
    """CSV 'first,last,CC' (numeric addresses) -> sorted (first, last, cc) with the low `shift` bits dropped."""
    rows = []
    for line in open(path):
        a, b, cc = line.strip().split(",")
        rows.append((int(a) >> shift, int(b) >> shift, cc))
    rows.sort()
    return rows


def ranges(rows, idx, unk):
    """Only range starts are kept; a gap (unassigned space) is a range with the "unknown" value."""
    starts, vals, prev_end = [], [], -1
    for a, b, cc in rows:
        if a > prev_end + 1:
            starts.append(prev_end + 1); vals.append(unk)
        if vals and vals[-1] == idx[cc] and a <= prev_end + 1:
            pass
        elif starts and starts[-1] == a:      # (IPv6 at /64: a smaller block inside the same /64) last one wins
            vals[-1] = idx[cc]
        else:
            starts.append(a); vals.append(idx[cc])
        prev_end = max(prev_end, b)
    starts.append(prev_end + 1); vals.append(unk)
    return starts, vals


pk = npm_pack("@ip-location-db/dbip-country")
v4 = read(os.path.join(pk, "dbip-country-ipv4-num.csv"), 0)
v6 = read(os.path.join(pk, "dbip-country-ipv6-num.csv"), 64)   # IPv6 by /64 prefix: no country block is smaller
codes = sorted({r[2] for r in v4} | {r[2] for r in v6})
idx = {c: i for i, c in enumerate(codes)}
s4, c4 = ranges(v4, idx, len(codes))
s6, c6 = ranges(v6, idx, len(codes))
s6[-1] = min(s6[-1], (1 << 64) - 1)
blob4 = zlib.compress(struct.pack(">%dI" % len(s4), *s4) + bytes(c4), 9)
blob6 = zlib.compress(struct.pack(">%dQ" % len(s6), *s6) + bytes(c6), 9)
with open(os.path.join(OUT, "geo_data.py"), "w") as f:
    f.write('"""IPv4 / IPv6 -> country data derived from DB-IP Lite (https://db-ip.com), CC BY 4.0. Generated by '
            'tools/build_geo.py.\nIPv6 ranges are by /64 prefix (BLOB6 holds the upper 64 bits)."""\n')
    f.write("CODES = %r\nCOUNT = %d\nBLOB = %r\nCOUNT6 = %d\nBLOB6 = %r\n" % (
        codes, len(s4), base64.b64encode(blob4).decode(), len(s6), base64.b64encode(blob6).decode()))
print("IPv4 ranges:", len(s4), "IPv6 ranges:", len(s6), "countries:", len(codes),
      "KB:", len(blob4) // 1024, "+", len(blob6) // 1024)
if "--ip-only" in sys.argv:
    sys.exit(0)

# ---- flags + names
fp = npm_pack("flag-icons")
names = {c["code"].upper(): c["name"] for c in json.load(open(os.path.join(fp, "country.json")))}
flags = {}
for cc in codes:
    svg = os.path.join(fp, "flags", "4x3", cc.lower() + ".svg")
    if not os.path.exists(svg):
        continue
    pair = []
    for w, h in ((20, 15), (40, 30)):
        png = subprocess.check_output(["rsvg-convert", "-w", str(w), "-h", str(h), svg])
        pair.append(base64.b64encode(zlib.compress(png, 9)).decode())
    flags[cc] = pair
with open(os.path.join(OUT, "flags_data.py"), "w") as f:
    f.write('"""Country names and 20x15 / 40x30 PNG flags (zlib+base64) from flag-icons (MIT). Generated by tools/build_geo.py."""\n')
    f.write("NAMES = %r\nFLAGS = %r\n" % ({c: names.get(c, c) for c in codes}, flags))
print("flags:", len(flags), "missing:", [c for c in codes if c not in flags])
